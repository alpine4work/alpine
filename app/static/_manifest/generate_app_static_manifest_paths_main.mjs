import fs from "fs/promises";
// eslint-disable-next-line sort-imports-by-source
import {appStaticPaths as oldAppStaticPaths} from "./app_static_manifest_paths.js";

async function main() {
    const [outputPath, ...newAppStaticPaths] = process.argv.slice(2);

    const newAppStaticPathPrefix = "app/static/";

    const appStaticPaths = Array.from(
        new Set([
            ...oldAppStaticPaths,
            ...newAppStaticPaths.map(path => {
                if (!path.startsWith(newAppStaticPathPrefix)) {
                    throw new Error(`Expected "${path}" to be in "${newAppStaticPathPrefix}"`);
                }

                return path.slice(newAppStaticPathPrefix.length - 1);
            }),
        ]),
    ).sort();

    const outputContents = `\
// @generated by //app/static:write_manifest_paths

/**
 * All app static file paths (excluding Remix build assets). In other words all
 * file paths provided by \`//app/static\` which excludes Remix build assets.
 *
 * This is a generated file which must always have at least the file paths in
 * \`//app/static\`. However, we may have more paths! When you delete a file
 * from \`//app/static\` it stays in this set. Since an old client in
 * production may need the deleted file. Our deploy script keeps old static
 * files around in Cloudflare R2 for 30 days after they've been removed for old
 * clients.
 *
 * You may manually delete old paths from this set and commit if you need to
 * reclaim a route that was previously served by a static file.
 */
export const appStaticManifestPaths: ReadonlySet<string> = new Set<string>([
${appStaticPaths.map(path => `    "${path}",\n`).join("")}]);
`;

    await fs.writeFile(outputPath, outputContents);
}

main().catch(error => {
    // eslint-disable-next-line no-console
    console.error(error);
    process.exitCode = 1;
});
