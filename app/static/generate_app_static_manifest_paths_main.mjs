import fs from "fs/promises";
// eslint-disable-next-line cyberworlds/sort-imports-by-source
import {appStaticManifestPaths as oldAppStaticManifestPaths} from "./app_static_manifest_paths.js";

/**
 * Expand static roots and regenerate the sorted application static manifest.
 */
async function main() {
    const [outputPath, ...appStaticManifestInputs] = process.argv.slice(2);

    const newAppStaticManifestPathPrefix = "app/static/files/";
    const openGraphImageManifestPathPrefix = "app/docs/codegen/open_graph_images_";
    const newAppStaticManifestPaths = [];

    for (const path of appStaticManifestInputs) {
        if (path.startsWith(newAppStaticManifestPathPrefix)) {
            const stat = await fs.stat(path);
            if (stat.isDirectory()) {
                await addDirectoryPaths(path);
            } else {
                addStaticFilePath(path);
            }
            continue;
        }

        if (path.startsWith(openGraphImageManifestPathPrefix) && path.endsWith(".json")) {
            const images = JSON.parse(await fs.readFile(path, "utf8"));
            if (!Array.isArray(images)) {
                throw new Error(`Expected Open Graph image array in \`${path}\``);
            }
            for (const image of images) {
                if (
                    typeof image !== "object" ||
                    image === null ||
                    typeof image.pageUrl !== "string" ||
                    !image.pageUrl.startsWith("/")
                ) {
                    throw new Error(`Expected Open Graph image page URL in \`${path}\``);
                }
                newAppStaticManifestPaths.push(`${image.pageUrl}/og.png`);
            }
            continue;
        }

        throw new Error(`Unexpected app static manifest input \`${path}\``);
    }

    /** Recursively add every file beneath a generated static directory. */
    async function addDirectoryPaths(directoryPath) {
        const entries = await fs.readdir(directoryPath, {withFileTypes: true});
        for (const entry of entries) {
            const path = `${directoryPath}/${entry.name}`;
            if (entry.isDirectory()) {
                await addDirectoryPaths(path);
            } else {
                addStaticFilePath(path);
            }
        }
    }

    /** Convert one static-file exec path into its public URL path. */
    function addStaticFilePath(path) {
        if (!path.startsWith(newAppStaticManifestPathPrefix)) {
            throw new Error(`Expected \`${path}\` to be in \`${newAppStaticManifestPathPrefix}\``);
        }
        newAppStaticManifestPaths.push(path.slice(newAppStaticManifestPathPrefix.length - 1));
    }

    const appStaticManifestPaths = Array.from(
        new Set([...oldAppStaticManifestPaths, ...newAppStaticManifestPaths]),
    ).sort();

    /* eslint-disable cyberworlds/string-quotes */

    const outputContents = `\
// @generated by //app/static:write_manifest_paths

/**
 * All app static file paths (excluding Remix build assets), including generated
 * documentation Open Graph images.
 *
 * This is a generated file which must always have at least the file paths in
 * \`//app/static\`. However, we may have more paths! When you delete a file from
 * \`//app/static\` it stays in this set. Since an old client in production may need
 * the deleted file. Our deploy script keeps old static files around in Cloudflare
 * R2 for 30 days after they've been removed for old clients.
 *
 * You may manually delete old paths from this set and commit if you need to
 * reclaim a route that was previously served by a static file.
 */
export const appStaticManifestPaths: ReadonlySet<string> = new Set<string>([
${appStaticManifestPaths.map(path => `    "${path}",\n`).join("")}]);
`;

    /* eslint-enable cyberworlds/string-quotes */

    await fs.writeFile(outputPath, outputContents);
}

main().catch(error => {
    // eslint-disable-next-line no-console
    console.error(error);
    process.exitCode = 1;
});
