import fs from "fs/promises";
import {produce} from "immer";
import Mustache from "mustache";
import openapiTypescript, {astToString} from "openapi-typescript";
import {join as joinPath} from "path";
// @ts-expect-error: After upgrading Prettier, we need to directly import
// `prettier/index.mjs` to make sure we don't get the standalone build.
// However, there's no blessed way from Prettier to import the full version
// with types.
import * as prettier from "prettier/index.mjs";
import ts from "typescript";
import Yaml from "yaml";
import {runfilesPath} from "~/server/helpers/node/runfiles_path.js";
import {contentCodeBlockLanguageIds} from "~/shared/content/content_code_block_language_id.js";
import {InternalError} from "~/shared/error/error.js";
import {
    fileAdditionalContentTypesAndExtensionsByContentType,
    fileContentTypeByCodeBlockLanguageId,
    fileContentTypes,
    getFileContentTypePreferredExtension,
} from "~/shared/files/file_content_type.js";
import {runAllPromises} from "~/shared/helpers/async/run_all_promises.js";
import {assert} from "~/shared/helpers/control/assert.js";
import {getOrSetDefaultMapValue} from "~/shared/helpers/map/get_or_set_default_map_value.js";
import {hasOwnProperty} from "~/shared/helpers/object/has_own_property.js";
import {isObject} from "~/shared/helpers/object/is_object.js";
import {quote} from "~/shared/helpers/string/quote.js";
import {idRegExp} from "~/shared/id/id_reg_exp.js";
import {maxLabelStringLength} from "~/shared/schema/helpers/label_string_schema.js";
import {taskTitleMaxLength} from "~/shared/tasks/title/task_title.js";

async function main() {
    /* ========================================================================== *\
     *                       Render YAML Mustache template                        *
    \* ========================================================================== */

    const originalSpecificationContent = await fs.readFile(
        joinPath(runfilesPath, "cyberworlds/shared/api/specification/api_specification.yaml"),
        "utf8",
    );

    let specificationContent = Mustache.render(
        originalSpecificationContent,
        {
            idRegExp: idRegExp.source,
            integerRegExp: "(?:[0-9]|[1-9][0-9]+)",
            maxLabelStringLength,
            taskTitleMaxLength,
            codeBlockLanguageIds: JSON.stringify(contentCodeBlockLanguageIds),
            fileContentTypes: JSON.stringify(Array.from(fileContentTypes).sort()),
        },
        undefined,
        {escape: string => string},
    );

    // Remove all comments from YAML. Comments are internal developer commentary that
    // shouldn't be included in the public API specification.
    specificationContent = specificationContent.replace(/^ *#[^\n]*\n+/gm, "");

    const parsedSpecification = Yaml.parse(specificationContent, {merge: true});

    specificationContent = Yaml.stringify(
        // Use `JSON.parse(JSON.stringify())` to get a deep copy of the schema so we don't
        // end up with YAML references like `&a2` + `*a2`. This improves readability for
        // the generated schema and makes the generated schema easier to code review.
        JSON.parse(JSON.stringify(specialize(parsedSpecification))),
        {indent: 4},
    );

    specificationContent =
        "# @generated by //shared/api/specification:write_specification\n\n" + specificationContent;

    /* ========================================================================== *\
     *                         Generate TypeScript types                          *
    \* ========================================================================== */

    const supportedIdTypes = [
        "AccountId",
        "BotId",
        "BotWebhookEventId",
        "ChannelId",
        "ChatId",
        "DocumentId",
        "DocumentThreadId",
        "FileId",
        "PostId",
        "SpaceId",
        "TaskId",
        "TaskCollectionId",
    ];

    const supportedIdTypeByMetadataPath = new Map(
        supportedIdTypes.map(idType => [`#/components/schemas/${idType}`, idType]),
    );

    function createTsIdType(name: string) {
        return ts.factory.createTypeReferenceNode(
            ts.factory.createQualifiedName(ts.factory.createIdentifier("IdTypes"), name),
        );
    }

    const specificationTypesAst = await openapiTypescript(specificationContent, {
        immutable: true,
        transform: (schema, options) => {
            if (schema.const === null) {
                return ts.factory.createLiteralTypeNode(ts.factory.createNull());
            }

            if (schema.format === "date-time") {
                return ts.factory.createTypeReferenceNode(
                    ts.factory.createIdentifier("DateString"),
                );
            }

            const supportedIdType = options.path
                ? supportedIdTypeByMetadataPath.get(options.path)
                : undefined;

            if (supportedIdType !== undefined) {
                assert(
                    schema.type === "string" &&
                        hasOwnProperty(schema, "pattern") &&
                        schema.pattern === `^${idRegExp.source}$`,
                    quote`Expected ${options.path} to have a string schema with \`pattern\` of \`^{{idRegExp}}$\``,
                );

                if (supportedIdType === "DocumentThreadId") {
                    return createTsIdType("DocumentCommentThreadId");
                } else {
                    return createTsIdType(supportedIdType);
                }
            }

            for (const [pathName, pathPrefix, idType] of [
                ["AccountPath", "/accounts", "AccountId"],
                ["ChannelPath", "/channels", "ChannelId"],
                ["ChatPath", "/chats", "ChatId"],
                ["DocumentPath", "/documents", "DocumentId"],
                ["PostPath", "/posts", "PostId"],
                ["TaskPath", "/tasks", "TaskId"],
                ["TaskCollectionPath", "/task-collections", "TaskCollectionId"],
            ] as const) {
                if (options.path === `#/components/schemas/${pathName}`) {
                    return ts.factory.createTemplateLiteralType(
                        ts.factory.createTemplateHead(`${pathPrefix}/`),
                        [
                            ts.factory.createTemplateLiteralTypeSpan(
                                createTsIdType(idType),
                                ts.factory.createTemplateTail(""),
                            ),
                        ],
                    );
                }
            }

            for (const [pathName, pathPrefix, idType] of [
                ["ChatMessagesListPath", "/chats/", "ChatId"],
                ["PostMessagesListPath", "/posts/", "PostId"],
                ["TaskMessagesListPath", "/tasks/", "TaskId"],
            ] as const) {
                if (options.path === `#/components/schemas/${pathName}`) {
                    return ts.factory.createTemplateLiteralType(
                        ts.factory.createTemplateHead(pathPrefix),
                        [
                            ts.factory.createTemplateLiteralTypeSpan(
                                createTsIdType(idType),
                                ts.factory.createTemplateTail("/messages"),
                            ),
                        ],
                    );
                }
            }

            for (const [pathName, pathPrefix, idType] of [
                ["ChatMessagePath", "/chats/", "ChatId"],
                ["PostMessagePath", "/posts/", "PostId"],
                ["TaskMessagePath", "/tasks/", "TaskId"],
            ] as const) {
                if (options.path === `#/components/schemas/${pathName}`) {
                    return ts.factory.createTemplateLiteralType(
                        ts.factory.createTemplateHead(pathPrefix),
                        [
                            ts.factory.createTemplateLiteralTypeSpan(
                                createTsIdType(idType),
                                ts.factory.createTemplateMiddle("/messages/"),
                            ),
                            ts.factory.createTemplateLiteralTypeSpan(
                                ts.factory.createKeywordTypeNode(ts.SyntaxKind.NumberKeyword),
                                ts.factory.createTemplateTail(""),
                            ),
                        ],
                    );
                }
            }

            // TODO(ifitzsimmons, #ai): There should probably be a better way to handle this?
            if (options.path === "#/components/schemas/DocumentThreadPath") {
                return ts.factory.createTemplateLiteralType(
                    ts.factory.createTemplateHead("/documents/"),
                    [
                        ts.factory.createTemplateLiteralTypeSpan(
                            createTsIdType("DocumentId"),
                            ts.factory.createTemplateMiddle("/threads/"),
                        ),
                        ts.factory.createTemplateLiteralTypeSpan(
                            createTsIdType("DocumentCommentThreadId"),
                            ts.factory.createTemplateTail(""),
                        ),
                    ],
                );
            }

            if (options.path === "#/components/schemas/DocumentMessagePath") {
                return ts.factory.createTemplateLiteralType(
                    ts.factory.createTemplateHead("/documents/"),
                    [
                        ts.factory.createTemplateLiteralTypeSpan(
                            createTsIdType("DocumentId"),
                            ts.factory.createTemplateMiddle("/threads/"),
                        ),
                        ts.factory.createTemplateLiteralTypeSpan(
                            createTsIdType("DocumentCommentThreadId"),
                            ts.factory.createTemplateMiddle("/messages/"),
                        ),
                        ts.factory.createTemplateLiteralTypeSpan(
                            ts.factory.createKeywordTypeNode(ts.SyntaxKind.NumberKeyword),
                            ts.factory.createTemplateTail(""),
                        ),
                    ],
                );
            }

            if (options.path === "#/components/schemas/DocumentThreadMessagesListPath") {
                return ts.factory.createTemplateLiteralType(
                    ts.factory.createTemplateHead("/documents/"),
                    [
                        ts.factory.createTemplateLiteralTypeSpan(
                            createTsIdType("DocumentId"),
                            ts.factory.createTemplateMiddle("/threads/"),
                        ),
                        ts.factory.createTemplateLiteralTypeSpan(
                            createTsIdType("DocumentCommentThreadId"),
                            ts.factory.createTemplateTail("/messages"),
                        ),
                    ],
                );
            }

            if (options.path === "#/components/schemas/TimeZone") {
                return ts.factory.createTypeReferenceNode(ts.factory.createIdentifier("TimeZone"));
            }
        },
    });

    let specificationTypesContent = astToString(specificationTypesAst);

    specificationTypesContent =
        // eslint-disable-next-line cyberworlds/string-quotes
        '// @generated by //shared/api/specification:write_specification\n/* eslint-disable @typescript-eslint/array-type */\n\nimport type {DateString} from "~/shared/helpers/date/date_string.js";import type {TimeZone} from "~/shared/helpers/intl/time_zone.js";\nimport type * as IdTypes from "~/shared/id/types/id_types.js";\n\nexport namespace ApiSpecification {' +
        specificationTypesContent +
        "}\n";

    const prettierConfig = await prettier.resolveConfig(
        joinPath(runfilesPath, "cyberworlds/prettier.config.cjs"),
    );

    specificationTypesContent = await prettier.format(specificationTypesContent, {
        ...prettierConfig,
        parser: "typescript",
    });

    const codeBlockLanguageDefinitionMapContent = contentCodeBlockLanguageIds
        .map(languageId => {
            const contentType = fileContentTypeByCodeBlockLanguageId[languageId];

            const extensions = [
                getFileContentTypePreferredExtension(contentType),
                ...(fileAdditionalContentTypesAndExtensionsByContentType[contentType]?.extensions ??
                    []),
            ];

            return `    ${languageId}: [${extensions
                .map(extension => JSON.stringify(extension))
                .join(", ")}],\n`;
        })
        .join("");

    const codeBlockLanguageDefinitionContent = `// @generated by //shared/api/specification:write_specification\n\n// prettier-ignore\nexport const apiContentCodeBlockLanguageDefinition = {
${codeBlockLanguageDefinitionMapContent}};\n`;

    /* ========================================================================== *\
     *                                Write files                                 *
    \* ========================================================================== */

    await runAllPromises([
        fs.writeFile(
            "shared/api/specification/api_specification_final_generated.yaml",
            specificationContent,
        ),
        fs.writeFile(
            "shared/api/specification/types/api_specification_types_generated.ts",
            specificationTypesContent,
        ),
        fs.writeFile(
            "shared/api/specification/api_content_code_block_language_definition_generated.ts",
            codeBlockLanguageDefinitionContent,
        ),
    ]);
}

main().catch(error => {
    // eslint-disable-next-line no-console
    console.error(error);
    process.exitCode = 1;
});

/**
 * API specification specialization is similar to C++ templates. It allows us to
 * conveniently declare multiple versions of the same underlying schema.
 *
 * For any schema that ends with `_${specialization}`, we create a copy of ALL
 * schemas that reference the original schema and reference the specialization
 * instead. This is useful if you want to have a specialized "input" version of
 * schemas that doesn't require all the properties of the "output" schema.
 *
 * This is an idea taken from programming languages like C++ and Rust.
 *
 * # Example
 *
 * In our schema we have `ContentMentionInlineElement` and
 * `ContentMentionInlineElement_Response`. `ContentMentionInlineElement_Response`
 * contains data loaded from the mention target (e.g. `title` and eventually data
 * like the task status). However when creating a mention the user won't have this
 * data available so they'll simply use `ContentMentionInlineElement` which does
 * not include this data.
 *
 * So this distinction needs to bubble all the way up the JSON schema. Ultimately
 * we need both a `Content` schema and a `Content_Response` schema. Where `Content`
 * references `ContentMentionInlineElement` and `Content_Response` references
 * `ContentMentionInlineElement_Response`.
 *
 * This specialization function performs this "bubbling". Generating a `_Response`
 * specialization for each schema that references `ContentMentionInlineElement`.
 */
function specialize(specification: unknown) {
    let iterationCount = 0;
    let specializationsBySchemaName = findSpecializations(specification);

    // NOTE(calebmer): This implementation isn't particularly efficient. It's looping
    // until we reach a "fix point". A point at which there are no new specializations
    // to add. On large schemas, this can get expensive fast. This algorithm is in the
    // neighborhood of O(n^2) though not as bad.
    //
    // We'll need some fancy algorithms here in the future to make this more efficient.
    while (specializationsBySchemaName.size > 0) {
        iterationCount++;

        if (iterationCount > 1000) throw new InternalError("Too many iterations");

        specializationsBySchemaName = applySpecializations(
            specializationsBySchemaName,
            specification,
        );
    }

    // Finally, replace any references in requests/responses with the corresponding
    // specialized schema.
    specializeRequestBodiesAndResponses(specification);

    return specification;
}

function findSpecializations(specification: unknown) {
    assert(isObject(specification));
    assert(isObject(specification.components));
    assert(isObject(specification.components.schemas));

    const specializationsBySchemaName = new Map<string, Array<string>>();

    for (const key of Object.keys(specification.components.schemas)) {
        if (!key.includes("_")) continue;

        const [schemaName = "", specialization = ""] = key.split("_", 2);

        getOrSetDefaultMapValue(specializationsBySchemaName, schemaName, () => []).push(
            specialization,
        );
    }

    return specializationsBySchemaName;
}

function applySpecializations(
    specializationsBySchemaName: Map<string, Array<string>>,
    specification: unknown,
) {
    assert(isObject(specification));
    assert(isObject(specification.components));
    assert(isObject(specification.components.schemas));

    const newSpecializationsBySchemaName = new Map<string, Array<string>>();
    const schemaNamesBySpecialization = new Map<string, Set<string>>();

    for (const [schemaName, specializations] of specializationsBySchemaName) {
        for (const specialization of specializations) {
            getOrSetDefaultMapValue(
                schemaNamesBySpecialization,
                specialization,
                () => new Set(),
            ).add(schemaName);
        }
    }

    for (const [specialization, schemaNames] of schemaNamesBySpecialization) {
        for (const [otherSchemaName, otherSchema] of Object.entries(
            specification.components.schemas,
        )) {
            let isAlreadySpecialized: boolean;
            let otherSpecializedSchemaName: string;

            if (!otherSchemaName.includes("_")) {
                isAlreadySpecialized = false;
                otherSpecializedSchemaName = `${otherSchemaName}_${specialization}`;
            } else if (otherSchemaName.endsWith(`_${specialization}`)) {
                isAlreadySpecialized = true;
                otherSpecializedSchemaName = otherSchemaName;
            } else {
                continue;
            }

            const otherSpecializedSchema =
                specification.components.schemas[otherSpecializedSchemaName] ?? otherSchema;

            const newOtherSpecializedSchema = produce(otherSpecializedSchema, otherSchema =>
                applySpecializationToSchema(specialization, schemaNames, otherSchema),
            );

            if (newOtherSpecializedSchema !== otherSpecializedSchema) {
                specification.components.schemas[otherSpecializedSchemaName] =
                    newOtherSpecializedSchema;

                // If this schema was already specialized, we don't need to recursively specialize
                // references for this schema again.
                if (!isAlreadySpecialized) {
                    getOrSetDefaultMapValue(
                        newSpecializationsBySchemaName,
                        otherSchemaName,
                        () => [],
                    ).push(specialization);
                }
            }
        }
    }

    return newSpecializationsBySchemaName;
}

function applySpecializationToSchema(
    specialization: string,
    schemaNames: Set<string>,
    value: unknown,
) {
    if (!isObject(value)) return;

    for (const [key, keyValue] of Object.entries(value)) {
        if (typeof keyValue === "string" && keyValue.startsWith("#/components/schemas/")) {
            const referencedSchemaName = keyValue.slice("#/components/schemas/".length);

            if (schemaNames.has(referencedSchemaName)) {
                value[key] = `#/components/schemas/${referencedSchemaName}_${specialization}`;
            }
        }

        applySpecializationToSchema(specialization, schemaNames, keyValue);
    }
}

function specializeRequestBodiesAndResponses(specification: unknown) {
    assert(isObject(specification));
    assert(isObject(specification.components));
    assert(isObject(specification.components.schemas));
    assert(isObject(specification.components.requestBodies));
    assert(isObject(specification.components.responses));
    assert(isObject(specification.paths));
    assert(isObject(specification.webhooks));

    const {schemas} = specification.components;

    for (const pathValue of Object.values(specification.paths)) {
        assert(isObject(pathValue));

        for (const [method, methodValue] of Object.entries(pathValue)) {
            if (method === "parameters") continue;

            assert(isObject(methodValue));

            specializeRequestBodies(schemas, methodValue.requestBody);
            specializeResponses(schemas, methodValue.responses);
        }
    }

    for (const webhookValue of Object.values(specification.webhooks)) {
        assert(isObject(webhookValue));

        for (const [method, methodValue] of Object.entries(webhookValue)) {
            if (method === "parameters") continue;

            assert(isObject(methodValue));

            specializeRequestBodies(schemas, methodValue.requestBody);
            specializeResponses(schemas, methodValue.responses);
        }
    }

    specializeRequestBodies(schemas, specification.components.requestBodies);
    specializeResponses(schemas, specification.components.responses);
}

function specializeRequestBodies(schemas: Record<string, unknown>, value: unknown) {
    if (!isObject(value)) return;

    for (const [key, keyValue] of Object.entries(value)) {
        if (typeof keyValue === "string" && keyValue.startsWith("#/components/schemas/")) {
            const referencedSchemaName = keyValue.slice("#/components/schemas/".length);

            if (hasOwnProperty(schemas, `${referencedSchemaName}_Request`)) {
                value[key] = `#/components/schemas/${referencedSchemaName}_Request`;
            }
        }

        specializeRequestBodies(schemas, keyValue);
    }
}

function specializeResponses(schemas: Record<string, unknown>, value: unknown) {
    if (!isObject(value)) return;

    for (const [key, keyValue] of Object.entries(value)) {
        if (typeof keyValue === "string" && keyValue.startsWith("#/components/schemas/")) {
            const referencedSchemaName = keyValue.slice("#/components/schemas/".length);

            if (hasOwnProperty(schemas, `${referencedSchemaName}_Response`)) {
                value[key] = `#/components/schemas/${referencedSchemaName}_Response`;
            }
        }

        specializeResponses(schemas, keyValue);
    }
}
