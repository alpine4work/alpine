async function main() {
    /* ========================================================================== *\
     *                       Render YAML Mustache template                        *
    \* ========================================================================== */

    const originalSpecificationContent = await fs.readFile(
        joinPath(runfilesPath, "cyberworlds/shared/api/specification/api_specification.yaml"),
        "utf8",
    );

    let specificationContent = Mustache.render(
        originalSpecificationContent,
        {
            idRegExp: idRegExp.source,
            integerRegExp: "(?:[0-9]|[1-9][0-9]+)",
            maxLabelStringLength,
            taskTitleMaxLength,
            fileAnalysisCaptionMaxLength,
            codeBlockLanguageIds: JSON.stringify(contentCodeBlockLanguageIds),
            fileContentTypes: JSON.stringify(Array.from(fileContentTypes).sort()),
        },
        undefined,
        {escape: string => string},
    );

    // Remove all comments from YAML. Comments are internal developer commentary that
    // shouldn't be included in the public API specification.
    specificationContent = specificationContent.replace(/^ *#[^\n]*\n+/gm, "");

    const parsedSpecification = Yaml.parse(specificationContent, {merge: true});

    const specializedSpecification = specialize(parsedSpecification);
    eliminateDeadApiSpecificationSchemas(specializedSpecification);

    specificationContent = Yaml.stringify(
        // Use `JSON.parse(JSON.stringify())` to get a deep copy of the schema so we don't
        // end up with YAML references like `&a2` + `*a2`. This improves readability for
        // the generated schema and makes the generated schema easier to code review.
        JSON.parse(JSON.stringify(specializedSpecification)),
        {indent: 4},
    );

    specificationContent =
        "# @generated by //shared/api/specification:write_specification\n\n" + specificationContent;

    /* ========================================================================== *\
     *                         Generate TypeScript types                          *
    \* ========================================================================== */

    const supportedIdTypes = [
        "AccountId",
        "BotId",
        "BotWebhookEventId",
        "ChannelId",
        "ChatId",
        "DocumentId",
        "DocumentThreadId",
        "FileId",
        "PostId",
        "SiteId",
        "SpaceId",
        "TaskId",
        "TaskCollectionId",
    ];

    const supportedIdTypeByMetadataPath = new Map(
        supportedIdTypes.map(idType => [`#/components/schemas/${idType}`, idType]),
    );

    function createTsIdType(name: string) {
        return ts.factory.createTypeReferenceNode(
            ts.factory.createQualifiedName(ts.factory.createIdentifier("IdTypes"), name),
        );
    }

    const specificationTypesAst = await openapiTypescript(specificationContent, {
        immutable: true,
        transform: (schema, options) => {
            if (schema.const === null) {
                return ts.factory.createLiteralTypeNode(ts.factory.createNull());
            }

            if (schema.format === "date-time") {
                return ts.factory.createTypeReferenceNode(
                    ts.factory.createIdentifier("DateString"),
                );
            }

            const supportedIdType = options.path
                ? supportedIdTypeByMetadataPath.get(options.path)
                : undefined;

            if (supportedIdType !== undefined) {
                assert(
                    schema.type === "string" &&
                        hasOwnProperty(schema, "pattern") &&
                        schema.pattern === `^${idRegExp.source}$`,
                    quote`Expected ${options.path} to have a string schema with \`pattern\` of \`^{{idRegExp}}$\``,
                );

                if (supportedIdType === "DocumentThreadId") {
                    return createTsIdType("DocumentCommentThreadId");
                } else {
                    return createTsIdType(supportedIdType);
                }
            }

            if (options.path === "#/components/schemas/ContentKey") {
                return ts.factory.createTypeReferenceNode(
                    ts.factory.createIdentifier("ApiContentKey"),
                );
            }

            if (options.path === "#/components/schemas/TaskQueryCursor") {
                return ts.factory.createTypeReferenceNode(
                    ts.factory.createIdentifier("ApiTaskQueryCursor"),
                );
            }

            for (const [pathName, pathPrefix, idType] of [
                ["AccountPath", "/accounts", "AccountId"],
                ["ChannelPath", "/channels", "ChannelId"],
                ["ChatPath", "/chats", "ChatId"],
                ["DocumentPath", "/documents", "DocumentId"],
                ["PostPath", "/posts", "PostId"],
                ["TaskPath", "/tasks", "TaskId"],
                ["TaskCollectionPath", "/task-collections", "TaskCollectionId"],
            ] as const) {
                if (options.path === `#/components/schemas/${pathName}`) {
                    return ts.factory.createTemplateLiteralType(
                        ts.factory.createTemplateHead(`${pathPrefix}/`),
                        [
                            ts.factory.createTemplateLiteralTypeSpan(
                                createTsIdType(idType),
                                ts.factory.createTemplateTail(""),
                            ),
                        ],
                    );
                }
            }

            for (const [pathName, pathPrefix, idType] of [
                ["ChatMessagesListPath", "/chats/", "ChatId"],
                ["PostMessagesListPath", "/posts/", "PostId"],
                ["TaskMessagesListPath", "/tasks/", "TaskId"],
            ] as const) {
                if (options.path === `#/components/schemas/${pathName}`) {
                    return ts.factory.createTemplateLiteralType(
                        ts.factory.createTemplateHead(pathPrefix),
                        [
                            ts.factory.createTemplateLiteralTypeSpan(
                                createTsIdType(idType),
                                ts.factory.createTemplateTail("/messages"),
                            ),
                        ],
                    );
                }
            }

            for (const [pathName, pathPrefix, idType] of [
                ["ChatMessagePath", "/chats/", "ChatId"],
                ["PostMessagePath", "/posts/", "PostId"],
                ["TaskMessagePath", "/tasks/", "TaskId"],
            ] as const) {
                if (options.path === `#/components/schemas/${pathName}`) {
                    return ts.factory.createTemplateLiteralType(
                        ts.factory.createTemplateHead(pathPrefix),
                        [
                            ts.factory.createTemplateLiteralTypeSpan(
                                createTsIdType(idType),
                                ts.factory.createTemplateMiddle("/messages/"),
                            ),
                            ts.factory.createTemplateLiteralTypeSpan(
                                ts.factory.createKeywordTypeNode(ts.SyntaxKind.NumberKeyword),
                                ts.factory.createTemplateTail(""),
                            ),
                        ],
                    );
                }
            }

            // TODO(ifitzsimmons, #ai): There should probably be a better way to handle this?
            if (options.path === "#/components/schemas/DocumentThreadPath") {
                return ts.factory.createTemplateLiteralType(
                    ts.factory.createTemplateHead("/documents/"),
                    [
                        ts.factory.createTemplateLiteralTypeSpan(
                            createTsIdType("DocumentId"),
                            ts.factory.createTemplateMiddle("/threads/"),
                        ),
                        ts.factory.createTemplateLiteralTypeSpan(
                            createTsIdType("DocumentCommentThreadId"),
                            ts.factory.createTemplateTail(""),
                        ),
                    ],
                );
            }

            if (options.path === "#/components/schemas/DocumentMessagePath") {
                return ts.factory.createTemplateLiteralType(
                    ts.factory.createTemplateHead("/documents/"),
                    [
                        ts.factory.createTemplateLiteralTypeSpan(
                            createTsIdType("DocumentId"),
                            ts.factory.createTemplateMiddle("/threads/"),
                        ),
                        ts.factory.createTemplateLiteralTypeSpan(
                            createTsIdType("DocumentCommentThreadId"),
                            ts.factory.createTemplateMiddle("/messages/"),
                        ),
                        ts.factory.createTemplateLiteralTypeSpan(
                            ts.factory.createKeywordTypeNode(ts.SyntaxKind.NumberKeyword),
                            ts.factory.createTemplateTail(""),
                        ),
                    ],
                );
            }

            if (options.path === "#/components/schemas/DocumentThreadMessagesListPath") {
                return ts.factory.createTemplateLiteralType(
                    ts.factory.createTemplateHead("/documents/"),
                    [
                        ts.factory.createTemplateLiteralTypeSpan(
                            createTsIdType("DocumentId"),
                            ts.factory.createTemplateMiddle("/threads/"),
                        ),
                        ts.factory.createTemplateLiteralTypeSpan(
                            createTsIdType("DocumentCommentThreadId"),
                            ts.factory.createTemplateTail("/messages"),
                        ),
                    ],
                );
            }

            if (options.path === "#/components/schemas/TimeZone") {
                return ts.factory.createTypeReferenceNode(ts.factory.createIdentifier("TimeZone"));
            }
        },
    });

    let specificationTypesContent = astToString(specificationTypesAst);

    specificationTypesContent =
        // eslint-disable-next-line cyberworlds/string-quotes
        '// @generated by //shared/api/specification:write_specification\n/* eslint-disable @typescript-eslint/array-type */\n\nimport type {ApiContentKey} from "~/shared/api/specification/types/api_content_key.open_source.js";import type {DateString} from "~/shared/helpers/date/date_string.open_source.js";import type {TimeZone} from "~/shared/helpers/intl/time_zone.open_source.js";import type {ApiTaskQueryCursor} from "~/shared/id/types/api_task_query_cursor.open_source.js";import type * as IdTypes from "~/shared/id/types/id_types.open_source.js";\n\nexport namespace ApiSpecification {' +
        specificationTypesContent +
        "}\n";

    const prettierConfig = await prettier.resolveConfig(
        joinPath(runfilesPath, "cyberworlds/prettier.config.cjs"),
    );

    specificationTypesContent = await prettier.format(specificationTypesContent, {
        ...prettierConfig,
        parser: "typescript",
    });

    const codeBlockLanguageDefinitionMapContent = contentCodeBlockLanguageIds
        .map(languageId => {
            const contentType = fileContentTypeByCodeBlockLanguageId[languageId];

            const extensions = [
                getFileContentTypePreferredExtension(contentType),
                ...(fileAdditionalContentTypesAndExtensionsByContentType[contentType]?.extensions ??
                    []),
            ];

            return `    ${languageId}: [${extensions
                .map(extension => JSON.stringify(extension))
                .join(", ")}],\n`;
        })
        .join("");

    const codeBlockLanguageDefinitionContent = `// @generated by //shared/api/specification:write_specification\n\n// prettier-ignore\nexport const apiContentCodeBlockLanguageDefinition = {
${codeBlockLanguageDefinitionMapContent}};\n`;

    /* ========================================================================== *\
     *                             Convenience types                              *
    \* ========================================================================== */

    // eslint-disable-next-line cyberworlds/string-quotes
    let specificationConvenienceTypesContent = `// @generated by //shared/api/specification:write_specification\n\nimport {ApiSpecification} from "~/shared/api/specification/types/api_specification_types.open_source.js";\n\n`;

    for (const schemaName of Object.keys(parsedSpecification.components.schemas)) {
        const typeName = "Api" + schemaName.replaceAll("_", "");

        // We already have IDs available in `shared/id/types/id_types.open_source.ts`.
        if (typeName.endsWith("Id")) continue;

        // Ignore some scalar type IDs that have one-to-one equivalents exported elsewhere.
        if (
            typeName === "ApiLabelString" ||
            typeName === "ApiDateTime" ||
            typeName === "ApiTimeZone" ||
            typeName === "ApiFileContentType" ||
            typeName === "ApiContentKey" ||
            typeName === "ApiTaskQueryCursor"
        ) {
            continue;
        }

        // eslint-disable-next-line cyberworlds/string-quotes
        specificationConvenienceTypesContent += `export type ${typeName} = ApiSpecification.components["schemas"]["${schemaName}"];\n\n`;
    }

    for (const schemaName of Object.keys(parsedSpecification.components.responses)) {
        const typeName = "Api" + schemaName + "Response";

        // eslint-disable-next-line cyberworlds/string-quotes
        specificationConvenienceTypesContent += `export type ${typeName} = ApiSpecification.components["responses"]["${schemaName}"]["content"]["application/json"];\n\n`;
    }

    for (const schemaName of Object.keys(parsedSpecification.components.requestBodies)) {
        const typeName = "Api" + schemaName + "RequestBody";

        // eslint-disable-next-line cyberworlds/string-quotes
        specificationConvenienceTypesContent += `export type ${typeName} = ApiSpecification.components["requestBodies"]["${schemaName}"]["content"]["application/json"];\n\n`;
    }

    for (const schemaName of Object.keys(parsedSpecification.webhooks)) {
        const typeName = "Api" + convertKebabCaseToPascalCase(schemaName) + "WebhookRequestBody";

        // eslint-disable-next-line cyberworlds/string-quotes
        specificationConvenienceTypesContent += `export type ${typeName} = ApiSpecification.webhooks["${schemaName}"]["post"]["requestBody"]["content"]["application/json"];\n\n`;
    }

    specificationConvenienceTypesContent = await prettier.format(
        specificationConvenienceTypesContent,
        {
            ...prettierConfig,
            parser: "typescript",
        },
    );

    /* ========================================================================== *\
     *                                Write files                                 *
    \* ========================================================================== */

    await runAllPromises([
        fs.writeFile(
            "shared/api/specification/api_specification_final_generated.yaml",
            specificationContent,
        ),
        fs.writeFile(
            "shared/api/specification/types/api_specification_types_generated.ts",
            specificationTypesContent,
        ),
        fs.writeFile(
            "shared/api/specification/types/api_specification_convenience_types_generated.ts",
            specificationConvenienceTypesContent,
        ),
        fs.writeFile(
            "shared/api/specification/api_content_code_block_language_definition_generated.ts",
            codeBlockLanguageDefinitionContent,
        ),
    ]);
}

main().catch(error => {
    // eslint-disable-next-line no-console
    console.error(error);
    process.exitCode = 1;
});

/** The prefix of a JSON schema reference into `components.schemas`. */
const schemaReferencePrefix = "#/components/schemas/";

/** The prefix of a local OpenAPI reference into `components`. */
const componentReferencePrefix = "#/components/";

/**
 * Removes component schemas that aren't transitively referenced by a path or
 * webhook. References to other components are followed as part of the traversal,
 * so a schema referenced by a reusable response or request body is preserved when
 * that component is reachable from an API root.
 */
function eliminateDeadApiSpecificationSchemas(specification: unknown) {
    assert(isObject(specification));
    assert(isObject(specification.components));
    assert(isObject(specification.components.schemas));
    assert(isObject(specification.paths));
    assert(isObject(specification.webhooks));

    const reachableSchemaNames = new Set<string>();
    const visitedValues = new Set<object>();
    const valuesToVisit: Array<unknown> = [specification.paths, specification.webhooks];

    while (valuesToVisit.length > 0) {
        const value = valuesToVisit.pop();
        if (!isObject(value)) continue;
        if (visitedValues.has(value)) continue;
        visitedValues.add(value);

        for (const keyValue of Object.values(value)) {
            if (typeof keyValue === "string" && keyValue.startsWith(componentReferencePrefix)) {
                if (keyValue.startsWith(schemaReferencePrefix)) {
                    const [encodedSchemaName] = keyValue
                        .slice(schemaReferencePrefix.length)
                        .split("/");

                    assert(encodedSchemaName !== undefined && encodedSchemaName !== "");
                    reachableSchemaNames.add(decodeJsonPointerPathPart(encodedSchemaName));
                }

                let referencedValue: unknown = specification;

                for (const encodedPathPart of keyValue.slice(2).split("/")) {
                    assert(
                        isObject(referencedValue),
                        quote`Cannot resolve API specification reference ${keyValue}`,
                    );

                    const pathPart = decodeJsonPointerPathPart(encodedPathPart);

                    assert(
                        hasOwnProperty(referencedValue, pathPart),
                        quote`Cannot resolve API specification reference ${keyValue}`,
                    );

                    referencedValue = referencedValue[pathPart];
                }

                valuesToVisit.push(referencedValue);
            }

            valuesToVisit.push(keyValue);
        }
    }

    for (const schemaName of Object.keys(specification.components.schemas)) {
        if (!reachableSchemaNames.has(schemaName)) {
            delete specification.components.schemas[schemaName];
        }
    }
}

/** Decodes a single RFC 6901 JSON Pointer path part. */
function decodeJsonPointerPathPart(encodedPathPart: string) {
    return encodedPathPart.replaceAll("~1", "/").replaceAll("~0", "~");
}

/**
 * API specification specialization is similar to C++ templates and Rust generic
 * monomorphization. It allows us to conveniently declare multiple versions
 * ("variants") of the same underlying schema without writing every one by hand.
 *
 * # Example
 *
 * In our schema we have `ContentMentionInlineElement` and
 * `ContentMentionInlineElement_Request`. `ContentMentionInlineElement` contains
 * data loaded from the mention reference (e.g. `title` and eventually data like
 * the task status). However when creating a mention the user won't have this data
 * available so they'll use `ContentMentionInlineElement_Request`, which does not
 * include this data.
 *
 * So this distinction needs to bubble all the way up the JSON schema. Ultimately
 * we need both a `Content` schema and a `Content_Request` schema. `Content`
 * references `ContentMentionInlineElement` and `Content_Request` references
 * `ContentMentionInlineElement_Request`. This function generates all the
 * intermediate variants even though only the leaf was written by hand.
 *
 * # The model
 *
 * - A schema name is a base name plus zero or more underscore-separated
 *   specializations. `ContentParagraphBlockElement_Request_WithoutKeys` is the
 *   `{Request, WithoutKeys}` variant of `ContentParagraphBlockElement`.
 *
 * - A variant is identified by its _set_ of specializations. The variants of a
 *   base schema are ordered by subset inclusion which makes them a lattice with
 *   the base schema (the empty set) at the bottom. Names spell the set in
 *   alphabetical order, so we write `Content_Request_WithoutKeys` and never
 *   `Content_WithoutKeys_Request`.
 *
 * - Resolution: a reference that asks for variant `v` of schema `S` resolves to
 *   the largest materialized variant that is a subset of `v` (ties broken by
 *   alphabetical order). So asking for `{Request, WithoutKeys}` uses
 *   `S_Request_WithoutKeys` if available, then `S_Request`, then `S_WithoutKeys`,
 *   and finally falls back to the base schema `S`.
 *
 * - Application: the body of variant `v` of `S` starts from the closest written
 *   variant of `S` and rewrites every schema reference `C_u` to
 *   `resolve(C, u ∪ v)`. The set union is what makes specializations compose: a
 *   reference to `Content_WithoutKeys` inside a schema being specialized for
 *   `Request` becomes a reference to `Content_Request_WithoutKeys`.
 *
 * - Demand: variants are only generated on demand, starting from the roots. Every
 *   hand-written schema demands itself, inbound request positions demand
 *   `u ∪ {Request}`, and response and outbound webhook positions demand `u` for
 *   every schema `C_u` they reference (both flavors are demanded for every schema
 *   reachable from the API surface when both can resolve, see the note on
 *   `rootReferencedSchemaNames` below), and rewriting a demanded variant demands
 *   `u ∪ v` for every reference. We iterate to the least fix point: the loop ends
 *   when no new variant materializes.
 *
 * - Materialization: a demanded variant only gets its own schema if its rewritten
 *   body is structurally different from the variant it would otherwise resolve to.
 *   This keeps the combinatorial explosion of variants in check: `SpaceId_Request`
 *   is never generated because nothing in `SpaceId` changes in a request, and
 *   `ContentInlineElement_Request_WithoutKeys` is never generated because no
 *   inline element has a `WithoutKeys` variant so it would be identical to
 *   `ContentInlineElement_Request`.
 *
 * Because generation is demand-driven from the request/response/webhook roots and
 * from hand-written schemas, a specialization combination that no reachable schema
 * distinguishes is never generated. Hand-written schemas are always preserved.
 */
// NOTE(calebmer, 2026-07-01): This was entirely rewritten by Fable to support
// multiple specializations at once. I didn't perform a thorough review. It looks
// good to me at a high level! I appreciate the applied academics. This felt like a
// mathy problem to me and Fable came up with a mathy solution.
function specialize(specification: unknown) {
    assert(isObject(specification));
    assert(isObject(specification.components));
    assert(isObject(specification.components.schemas));
    assert(isObject(specification.components.requestBodies));
    assert(isObject(specification.components.responses));
    assert(isObject(specification.paths));
    assert(isObject(specification.webhooks));

    const {schemas} = specification.components;

    // Index the hand-written variants of every base schema.
    const writtenVariantsByBaseSchemaName: SpecializationVariantsByBaseSchemaName = new Map();

    for (const schemaName of Object.keys(schemas)) {
        const {baseSchemaName, specializations} = parseSpecializedSchemaName(schemaName);
        const variant = createSpecializationVariant(baseSchemaName, specializations);

        assert(
            variant.schemaName === schemaName,
            quote`Expected schema ${schemaName} to spell its specializations in alphabetical order: ${variant.schemaName}`,
        );

        getOrSetDefaultMapValue(
            writtenVariantsByBaseSchemaName,
            baseSchemaName,
            () => new Map(),
        ).set(variant.specializationKey, variant);
    }

    // Add any properties in response schemas as optional properties to the schemas
    // used in request positions. This is needed to make sure we can accept a response
    // object as request input. Otherwise it would be rejected by
    // `additionalProperties: false`.
    addResponseAdditionalPropertiesToRequestSchema(schemas, writtenVariantsByBaseSchemaName);

    // Snapshot the written schema bodies. Variant bodies are always rewritten from
    // these pristine snapshots so reference rewrites from previous iterations never
    // compound. The deep copy also severs object sharing introduced by YAML anchors.
    const writtenSchemaBodiesBySchemaName = new Map<string, unknown>();

    for (const [schemaName, schemaBody] of Object.entries(schemas)) {
        writtenSchemaBodiesBySchemaName.set(schemaName, JSON.parse(JSON.stringify(schemaBody)));
    }

    // All materialized variants: the written ones plus every variant we generate.
    const materializedVariantsByBaseSchemaName: SpecializationVariantsByBaseSchemaName = new Map();

    for (const [baseSchemaName, writtenVariants] of writtenVariantsByBaseSchemaName) {
        materializedVariantsByBaseSchemaName.set(baseSchemaName, new Map(writtenVariants));
    }

    // Every variant demanded somewhere in the specification, keyed by the variant's
    // canonical schema name. Hand-written schemas demand themselves so their own
    // references get resolved.
    const demands = new Map<string, SpecializationVariant>();

    for (const writtenVariants of writtenVariantsByBaseSchemaName.values()) {
        for (const variant of writtenVariants.values()) {
            demands.set(variant.schemaName, variant);
        }
    }

    const addSpecializationDemand = (
        baseSchemaName: string,
        specializations: ReadonlySet<string>,
    ) => {
        const demand = createSpecializationVariant(baseSchemaName, specializations);

        if (!demands.has(demand.schemaName)) demands.set(demand.schemaName, demand);
    };

    // Resolve a schema reference found while rewriting a variant with the provided
    // specializations. The reference's own specializations and the variant's
    // specializations compose by set union. Also demands the union variant so we'll
    // generate it if it's structurally unique.
    const demandSchemaReference = (
        referencedSchemaName: string,
        specializations: ReadonlySet<string>,
    ) => {
        const reference = parseSpecializedSchemaName(referencedSchemaName);

        const targetSpecializations = new Set([...reference.specializations, ...specializations]);

        addSpecializationDemand(reference.baseSchemaName, targetSpecializations);

        const resolvedVariant = resolveSpecializationVariant(
            materializedVariantsByBaseSchemaName,
            reference.baseSchemaName,
            targetSpecializations,
        );

        assert(
            resolvedVariant !== undefined,
            quote`Cannot resolve schema reference ${referencedSchemaName}`,
        );

        return resolvedVariant.schemaName;
    };

    // Inbound API request positions demand the `Request` specialization of every
    // schema they reference. API responses and outbound webhook payloads demand the
    // base response schema. A webhook may explicitly reference a `_Request` schema
    // when it intentionally sends the more primitive request representation.
    const requestSpecializations: ReadonlySet<string> = new Set(["Request"]);
    const responseSpecializations: ReadonlySet<string> = new Set();

    const specializationRoots: Array<SpecializationRoot> = [];

    const addSpecializationRoot = (
        container: {[key: string]: unknown},
        containerKey: string,
        specializations: ReadonlySet<string>,
    ) => {
        const body = container[containerKey];
        if (body === undefined) return;

        specializationRoots.push({
            container,
            containerKey,
            body: JSON.parse(JSON.stringify(body)),
            specializations,
        });
    };

    for (const pathValue of Object.values(specification.paths)) {
        assert(isObject(pathValue));

        for (const [method, methodValue] of Object.entries(pathValue)) {
            if (method === "parameters") continue;

            assert(isObject(methodValue));

            addSpecializationRoot(methodValue, "requestBody", requestSpecializations);
            addSpecializationRoot(methodValue, "responses", responseSpecializations);
        }
    }

    for (const webhookValue of Object.values(specification.webhooks)) {
        assert(isObject(webhookValue));

        for (const [method, methodValue] of Object.entries(webhookValue)) {
            if (method === "parameters") continue;

            assert(isObject(methodValue));

            addSpecializationRoot(methodValue, "requestBody", responseSpecializations);
            addSpecializationRoot(methodValue, "responses", responseSpecializations);
        }
    }

    addSpecializationRoot(specification.components, "requestBodies", requestSpecializations);
    addSpecializationRoot(specification.components, "responses", responseSpecializations);

    // The API surface is bidirectional: every schema reachable from a request,
    // response, or webhook position gets both its base response flavor and its
    // `Request` flavor (when both flavors can resolve and are structurally distinct),
    // even if only one position references it today. Request-only schemas such as
    // `ChatCreate_Request` intentionally have no base response flavor.
    const rootReferencedSchemaNames = new Set<string>();

    for (const specializationRoot of specializationRoots) {
        collectSchemaReferenceNames(specializationRoot.body, rootReferencedSchemaNames);
    }

    for (const referencedSchemaName of rootReferencedSchemaNames) {
        const reference = parseSpecializedSchemaName(referencedSchemaName);

        for (const rootSpecializations of [requestSpecializations, responseSpecializations]) {
            const specializations = new Set([...reference.specializations, ...rootSpecializations]);

            if (
                resolveSpecializationVariant(
                    writtenVariantsByBaseSchemaName,
                    reference.baseSchemaName,
                    specializations,
                ) !== undefined
            ) {
                addSpecializationDemand(reference.baseSchemaName, specializations);
            }
        }
    }

    // Iterate to a fix point. Rewrites in one iteration may demand and materialize
    // variants that references resolved past in previous iterations, so we repeat
    // until no new variant materializes. The final iteration runs with a stable set of
    // variants which makes every rewritten body and root stable too.
    let iterationCount = 0;
    let materializedNewVariant = true;

    while (materializedNewVariant) {
        materializedNewVariant = false;

        iterationCount++;
        if (iterationCount > 1000) throw new InternalError("Too many iterations");

        // Rewrite the request/response/webhook roots from their pristine snapshots. This
        // both records their demands and, on the final iteration, writes the stable
        // rewritten roots back into the specification.
        for (const specializationRoot of specializationRoots) {
            specializationRoot.container[specializationRoot.containerKey] = rewriteSchemaReferences(
                specializationRoot.body,
                referencedSchemaName =>
                    demandSchemaReference(referencedSchemaName, specializationRoot.specializations),
            );
        }

        // Rewrite the body of every demanded variant from its written source. `Map`
        // iterators observe entries inserted during iteration so demands recorded by these
        // rewrites are processed by this same loop.
        const rewriteResultsBySchemaName = new Map<
            string,
            {sourceSchemaName: string; body: unknown}
        >();

        for (const demand of demands.values()) {
            const writtenVariant = resolveSpecializationVariant(
                writtenVariantsByBaseSchemaName,
                demand.baseSchemaName,
                demand.specializations,
            );

            assert(
                writtenVariant !== undefined,
                quote`Cannot find a written schema for ${demand.schemaName}`,
            );

            rewriteResultsBySchemaName.set(demand.schemaName, {
                sourceSchemaName: writtenVariant.schemaName,
                body: rewriteSchemaReferences(
                    writtenSchemaBodiesBySchemaName.get(writtenVariant.schemaName),
                    referencedSchemaName =>
                        demandSchemaReference(referencedSchemaName, demand.specializations),
                ),
            });
        }

        // Materialize demanded variants, least specialized first, so that a more
        // specialized variant always compares against the freshest less specialized
        // variant.
        const sortedDemands = Array.from(demands.values()).sort(
            (a, b) => a.specializations.size - b.specializations.size,
        );

        for (const demand of sortedDemands) {
            const rewriteResult = rewriteResultsBySchemaName.get(demand.schemaName);
            assert(rewriteResult !== undefined);

            const materializedVariant = materializedVariantsByBaseSchemaName
                .get(demand.baseSchemaName)
                ?.get(demand.specializationKey);

            // Already materialized (either hand-written or generated in a previous iteration):
            // refresh the body with the latest rewrite.
            if (materializedVariant !== undefined) {
                schemas[materializedVariant.schemaName] = rewriteResult.body;
                continue;
            }

            // If rewriting changed nothing then this demand resolves to the written schema it
            // was rewritten from and doesn't need its own schema. (`rewriteSchemaReferences()`
            // returns the input by reference when nothing changed.)
            if (
                rewriteResult.body ===
                writtenSchemaBodiesBySchemaName.get(rewriteResult.sourceSchemaName)
            ) {
                continue;
            }

            // If the rewritten body is structurally identical to the variant this demand
            // currently resolves to then it doesn't need its own schema either. For example,
            // `ContentInlineElement_Request_WithoutKeys` would be identical to
            // `ContentInlineElement_Request` because no inline element has a `WithoutKeys`
            // variant.
            const fallbackVariant = resolveSpecializationVariant(
                materializedVariantsByBaseSchemaName,
                demand.baseSchemaName,
                demand.specializations,
            );

            assert(fallbackVariant !== undefined, quote`Cannot resolve ${demand.schemaName}`);

            const fallbackRewriteResult = rewriteResultsBySchemaName.get(
                fallbackVariant.schemaName,
            );

            assert(fallbackRewriteResult !== undefined);

            if (JSON.stringify(rewriteResult.body) === JSON.stringify(fallbackRewriteResult.body)) {
                continue;
            }

            getOrSetDefaultMapValue(
                materializedVariantsByBaseSchemaName,
                demand.baseSchemaName,
                () => new Map(),
            ).set(demand.specializationKey, demand);

            schemas[demand.schemaName] = rewriteResult.body;
            materializedNewVariant = true;
        }
    }

    return specification;
}

/**
 * A single variant of a base schema, identified by its set of specializations. The
 * base schema itself is the variant with no specializations.
 */
type SpecializationVariant = {
    baseSchemaName: string;
    /** The canonical schema name for this variant (e.g. `Content_Request`). */
    schemaName: string;
    specializations: ReadonlySet<string>;
    /**
     * The alphabetically ordered specializations joined by `_`. Map key material.
     */
    specializationKey: string;
    /** The specializations in alphabetical order. */
    sortedSpecializations: ReadonlyArray<string>;
};

/** The variants of every base schema, indexed by their specialization key. */
type SpecializationVariantsByBaseSchemaName = Map<string, Map<string, SpecializationVariant>>;

/**
 * A place in the specification that demands specializations of the schemas it
 * references: a request, response, or webhook position. `body` is a pristine deep
 * copy of the original value at `container[containerKey]` that rewrites start
 * from.
 */
type SpecializationRoot = {
    container: {[key: string]: unknown};
    containerKey: string;
    body: unknown;
    specializations: ReadonlySet<string>;
};

/** Recursively collects the names of all referenced schemas. */
function collectSchemaReferenceNames(value: unknown, schemaNames: Set<string>) {
    if (!isObject(value)) return;

    for (const keyValue of Object.values(value)) {
        if (typeof keyValue === "string" && keyValue.startsWith(schemaReferencePrefix)) {
            schemaNames.add(keyValue.slice(schemaReferencePrefix.length));
        }

        collectSchemaReferenceNames(keyValue, schemaNames);
    }
}

/**
 * Splits a schema name into its base name and its specializations (e.g.
 * `Content_Request_WithoutKeys` has the base name `Content` and the
 * specializations `Request` and `WithoutKeys`).
 */
function parseSpecializedSchemaName(schemaName: string) {
    const [baseSchemaName = "", ...specializations] = schemaName.split("_");

    assert(baseSchemaName !== "", quote`Expected a base schema name in ${schemaName}`);

    for (const specialization of specializations) {
        assert(specialization !== "", quote`Expected a specialization name in ${schemaName}`);
    }

    assert(
        new Set(specializations).size === specializations.length,
        quote`Expected unique specializations in ${schemaName}`,
    );

    return {baseSchemaName, specializations};
}

/** Creates the `SpecializationVariant` for a set of specializations. */
function createSpecializationVariant(
    baseSchemaName: string,
    specializations: Iterable<string>,
): SpecializationVariant {
    const specializationsSet = new Set(specializations);
    const sortedSpecializations = Array.from(specializationsSet).sort();

    return {
        baseSchemaName,
        schemaName: [baseSchemaName, ...sortedSpecializations].join("_"),
        specializations: specializationsSet,
        specializationKey: sortedSpecializations.join("_"),
        sortedSpecializations,
    };
}

/**
 * Resolves the target specializations to the closest variant of the base schema:
 * the variant with the most specializations whose specializations are all a subset
 * of the target.
 */
function resolveSpecializationVariant(
    variantsByBaseSchemaName: SpecializationVariantsByBaseSchemaName,
    baseSchemaName: string,
    targetSpecializations: ReadonlySet<string>,
) {
    const variants = variantsByBaseSchemaName.get(baseSchemaName);
    if (variants === undefined) return undefined;

    let bestVariant: SpecializationVariant | undefined;

    for (const variant of variants.values()) {
        let isSubset = true;

        for (const specialization of variant.specializations) {
            if (!targetSpecializations.has(specialization)) {
                isSubset = false;
                break;
            }
        }

        if (!isSubset) continue;

        if (
            bestVariant === undefined ||
            compareSpecializationVariantPrecedence(variant, bestVariant) < 0
        ) {
            bestVariant = variant;
        }
    }

    return bestVariant;
}

/**
 * Orders variants for resolution: a variant with more specializations comes first,
 * ties are broken alphabetically so resolution is deterministic (e.g. `_Request`
 * is preferred over `_WithoutKeys` when both match and their combination doesn't
 * exist).
 */
function compareSpecializationVariantPrecedence(
    a: SpecializationVariant,
    b: SpecializationVariant,
) {
    if (a.specializations.size !== b.specializations.size) {
        return b.specializations.size - a.specializations.size;
    }

    for (let i = 0; i < a.sortedSpecializations.length; i++) {
        const aSpecialization = a.sortedSpecializations[i] ?? "";
        const bSpecialization = b.sortedSpecializations[i] ?? "";
        if (aSpecialization < bSpecialization) return -1;
        if (aSpecialization > bSpecialization) return 1;
    }

    return 0;
}

/**
 * Immutably rewrites every schema reference in `value` to the name returned by
 * `resolveSchemaReferenceName`. Returns `value` itself (by reference) when nothing
 * changed.
 */
function rewriteSchemaReferences(
    value: unknown,
    resolveSchemaReferenceName: (referencedSchemaName: string) => string,
) {
    return produce(value, draftValue => {
        rewriteSchemaReferencesInPlace(draftValue, resolveSchemaReferenceName);
    });
}

function rewriteSchemaReferencesInPlace(
    value: unknown,
    resolveSchemaReferenceName: (referencedSchemaName: string) => string,
) {
    if (!isObject(value)) return;

    for (const [key, keyValue] of Object.entries(value)) {
        if (typeof keyValue === "string" && keyValue.startsWith(schemaReferencePrefix)) {
            const referencedSchemaName = keyValue.slice(schemaReferencePrefix.length);
            const resolvedSchemaName = resolveSchemaReferenceName(referencedSchemaName);

            if (resolvedSchemaName !== referencedSchemaName) {
                value[key] = `${schemaReferencePrefix}${resolvedSchemaName}`;
            }
        }

        rewriteSchemaReferencesInPlace(keyValue, resolveSchemaReferenceName);
    }
}

/**
 * Adds any properties in response variants as optional properties to the schema
 * that the same object resolves to in request positions. This is needed to make
 * sure we can accept a response object as request input. Otherwise it would be
 * rejected by `additionalProperties: false`.
 *
 * A response variant is accepted in the request position that resolves the same
 * specializations plus `Request`. For example, `Task` objects must be accepted by
 * `Task_Request`, and `ContentFileBlockElement_WithoutKeys` objects must be
 * accepted by whatever `{Request, WithoutKeys}` resolves to.
 */
function addResponseAdditionalPropertiesToRequestSchema(
    schemas: {[key: string]: unknown},
    writtenVariantsByBaseSchemaName: SpecializationVariantsByBaseSchemaName,
) {
    for (const [schemaName, responseSchema] of Object.entries(schemas)) {
        const {baseSchemaName, specializations} = parseSpecializedSchemaName(schemaName);
        if (specializations.includes("Request")) continue;

        if (!isObject(responseSchema)) continue;
        if (responseSchema.type !== "object") continue;
        if (!isObject(responseSchema.properties)) continue;

        const responseSchemaProperties = responseSchema.properties;

        const targetVariant = resolveSpecializationVariant(
            writtenVariantsByBaseSchemaName,
            baseSchemaName,
            new Set([...specializations, "Request"]),
        );

        if (targetVariant === undefined || targetVariant.schemaName === schemaName) continue;

        const targetSchema = schemas[targetVariant.schemaName];

        if (!isObject(targetSchema)) continue;
        if (targetSchema.type !== "object") continue;

        assert(isObject(targetSchema.properties));

        for (const [propertyKey, propertySchema] of Object.entries(responseSchemaProperties)) {
            if (hasOwnProperty(targetSchema.properties, propertyKey)) continue;

            // @ts-expect-error: TypeScript doesn't like the type narrowing from
            // `hasOwnProperty()` above.
            targetSchema.properties[propertyKey] = JSON.parse(JSON.stringify(propertySchema));
        }
    }
}
