import fs from "fs-extra";
import {extname} from "path";
import * as prettier from "prettier";
import Yaml from "yaml";
import {runAllPromises} from "~/shared/helpers/async/run_all_promises.js";

async function main() {
    await runAllPromises(
        process.argv.slice(2).map(async templatePath => {
            const templateJsonContents = JSON.parse(await fs.readFile(templatePath, "utf8"));

            const templateYamlContents = new Yaml.Document();
            templateYamlContents.contents = templateJsonContents;

            const unformattedTemplateYamlString = templateYamlContents.toString({
                lineWidth: 100,
                indent: 4,
            });

            const templateYamlString = prettier.format(unformattedTemplateYamlString, {
                parser: "yaml",
                printWidth: 100,
                tabWidth: 4,
            });

            await fs.writeFile(
                `${templatePath.slice(0, -extname(templatePath).length)}.yaml`,
                `# @generated by //admin/aws:write_aws_app_templates\n\n${templateYamlString}`,
            );
        }),
    );
}

main().then(
    () => {
        process.exitCode = 0;
    },
    error => {
        // eslint-disable-next-line no-console
        console.error(error);
        process.exitCode = 1;
    },
);
